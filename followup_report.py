"""Tables and figures for the follow-up experiments (after the main sweep):
long-horizon rollout error of every run, fixed step count, learning rate, curriculum and damping,
and the trainability check (curvature of each unrolled run's own loss vs whether it descended).

  python followup_report.py   -> <out_root>/tables_followup.md, figs/fig8..fig10
Inputs: long_eval.pt (eval_long.py), trainability.pt (trainability.py), runs/*/meta.json.
"""
import argparse
import json
import os

import matplotlib
import numpy as np
import torch

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from msr.config import load_cfg  # noqa: E402

CLS = ["euler", "direct"]


def describe(run, meta):
    """Short protocol description from the run's metadata."""
    if meta["proto"] == "onestep":
        return "one-step"
    win = meta["p"] * meta["dt"]
    s = f"window {win:.2f} (p={meta['p']}), "
    s += "scratch" if meta["init"] == "scratch" else ("fine-tuned from " + (meta.get("from_run") or "one-step"))
    lr = meta.get("lr")
    if lr is not None:
        s += f", lr {lr:.0e}"
    if meta.get("gamma"):
        s += f", damped gamma={meta['gamma']:g}"
    return s


def rng(a):
    return f"{a.min():.2g}-{a.max():.2g}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cfg", default="config.yaml")
    a = ap.parse_args()
    cfg = load_cfg(a.cfg)
    R = cfg["out_root"]
    figs = os.path.join(R, "figs")
    os.makedirs(figs, exist_ok=True)
    meta = {}
    for d in os.listdir(os.path.join(R, "runs")):
        f = os.path.join(R, "runs", d, "meta.json")
        if os.path.exists(f):
            meta[d] = json.load(open(f))
    L = torch.load(os.path.join(R, "long_eval.pt"), weights_only=False)
    sat = L.pop("saturation_rms")
    Ts = cfg["long_horizons"]
    md = ["# Follow-up tables (generated by followup_report.py)", "",
          f"Rollout error |e(T)| on {cfg['n_test']} held-out starts, final checkpoints, min-max over 3 seeds. "
          f"Saturated-error scale (RMS distance of independent attractor states): {sat:.1f}.", ""]

    # ---------- long-horizon errors, every run
    for dt in sorted({m["dt"] for m in meta.values()}):
        runs = sorted([r for r in meta if meta[r]["dt"] == dt and (r, "euler", 0) in L],
                      key=lambda r: (meta[r]["proto"] != "onestep", meta[r]["p"] or 0, r))
        md += [f"### dt = {dt:g}", "", "| run | protocol | class | " + " | ".join(f"T={T:g}" for T in Ts) + " |",
               "|" + "---|" * (3 + len(Ts))]
        for r in runs:
            for c in CLS:
                arr = np.array([L[(r, c, s)]["e_norm"] for s in cfg["seeds"]])
                md.append(f"| {r} | {describe(r, meta[r])} | {c} | " + " | ".join(rng(arr[:, i]) for i in range(len(Ts))) + " |")
        md.append("")

    # ---------- figure: |e(T)| vs T for the key protocols (Euler)
    key = [("onestep", "one-step", "black"), ("unroll032_ft", "window 0.32, fine-tuned", "tab:blue"),
           ("unroll064_ft_cur", "window 0.64, curriculum", "tab:green"), ("unroll128g9_ft", "window 1.28, damped", "tab:purple"),
           ("unroll128_ft_cur", "window 1.28, curriculum", "tab:orange")]
    dts = sorted({m["dt"] for m in meta.values()})
    fig, axs = plt.subplots(2, len(dts), figsize=(3.4 * len(dts), 6.2), sharey=True)
    for j, dt in enumerate(dts):
        for i, c in enumerate(CLS):
            ax = axs[i, j]
            for suffix, lab, col in key:
                r = f"dt{dt:g}_{suffix}"
                if (r, c, 0) not in L:
                    continue
                arr = np.array([L[(r, c, s)]["e_norm"] for s in cfg["seeds"]])
                ax.plot(Ts, arr.mean(0), color=col, marker="o", ms=3, label=lab)
                ax.fill_between(Ts, arr.min(0), arr.max(0), color=col, alpha=0.2, lw=0)
            ax.set_xscale("log")
            ax.set_yscale("log")
            ax.set_title(f"{c}, dt={dt:g}", fontsize=8)
            if i == 1:
                ax.set_xlabel("physical time T")
            if j == 0:
                ax.set_ylabel("|e(T)|")
    axs[0, -1].legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(os.path.join(figs, "fig8_long_horizon.pdf"))
    plt.close(fig)

    # ---------- trainability
    tf = os.path.join(R, "trainability.pt")
    if os.path.exists(tf):
        T = torch.load(tf, weights_only=False)
        md += ["## Trainability: curvature of each unrolled run's own loss", "",
               "lam0 = largest Gauss-Newton eigenvalue of the run's training loss (its window and weights) at the start of "
               "training, on 512 held-out starts; descended = (own loss at the end) / (at the start) < 1. "
               "Fine-tuned runs only (scratch runs start from a random initialization).", "",
               "| run | protocol | class | lam0 (median) | lr x lam0 (median) | end/start per seed | largest spike per seed |",
               "|---|---|---|---|---|---|---|"]
        ft = {k: v for k, v in T.items() if v["init"] == "ft"}
        for r in sorted({k[0] for k in ft}, key=lambda r: (meta[r]["p"] * meta[r]["dt"], meta[r]["dt"], r)):
            for c in CLS:
                vs = [ft[(r, c, s)] for s in cfg["seeds"] if (r, c, s) in ft]
                md.append(f"| {r} | {describe(r, meta[r])} | {c} | {np.median([v['lam_start'] for v in vs]):.2g} | "
                          f"{np.median([v['lr_lam'] for v in vs]):.2g} | "
                          + ", ".join(f"{v['end_over_start']:.2g}" for v in vs) + " | "
                          + ", ".join(f"x{v['max_spike']:.2g}" for v in vs) + " |")
        md.append("")
        # curvature vs window (plain loss) and descent scatter
        fig, axs = plt.subplots(1, 2, figsize=(11, 4.3))
        ax = axs[0]
        cols = dict(zip(dts, plt.cm.viridis(np.linspace(0, 0.85, len(dts)))))
        for c, mk in (("euler", "o"), ("direct", "s")):
            for dt in dts:
                pts = sorted({(v["T_win"], v["lam_start"]) for k, v in ft.items()
                              if k[1] == c and v["dt"] == dt and not v["gamma"] and v["from_run"] is None})
                if pts:
                    w = sorted({p[0] for p in pts})
                    med = [np.median([p[1] for p in pts if p[0] == x]) for x in w]
                    ax.plot(w, med, marker=mk, color=cols[dt], ls="-" if c == "euler" else "--",
                            label=f"{c}, dt={dt:g}")
        ax.set_yscale("log")
        ax.set_xlabel("training window (physical time)")
        ax.set_ylabel("largest curvature of the training loss at start")
        ax.set_title("fine-tuned from one-step models, undamped loss", fontsize=8)
        ax.legend(fontsize=6, ncol=2)
        ax = axs[1]
        wins = sorted({v["T_win"] for v in ft.values()})
        wc = dict(zip(wins, plt.cm.plasma(np.linspace(0, 0.85, len(wins)))))
        for k, v in ft.items():
            ax.scatter(v["lr_lam"], v["end_over_start"], color=wc[v["T_win"]], marker="o" if k[1] == "euler" else "s",
                       s=14, alpha=0.8, edgecolors="k" if v["gamma"] else "none")
        for w in wins:
            ax.scatter([], [], color=wc[w], label=f"window {w:.2f}")
        ax.axhline(1, color="gray", lw=0.6)
        ax.axvline(2, color="gray", lw=0.6, ls=":")
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xlabel("peak lr x lam0  (gradient-descent stability limit ~2, dotted)")
        ax.set_ylabel("own loss: end / start")
        ax.set_title("circle Euler, square direct; black edge = damped loss", fontsize=8)
        ax.legend(fontsize=6)
        fig.tight_layout()
        fig.savefig(os.path.join(figs, "fig9_trainability.pdf"))
        plt.close(fig)
        x = np.array([v["lr_lam"] for v in ft.values()])
        lam = np.array([v["lam_start"] for v in ft.values()])
        win = np.array([v["T_win"] for v in ft.values()])
        y = np.array([v["end_over_start"] < 1 for v in ft.values()])

        def best(z):
            return max(((np.mean((z <= t) == y), t) for t in np.unique(z)), key=lambda q: q[0])
        md += ["Best single threshold separating runs that descended (fine-tuned, all classes): "
               + "; ".join(f"{n}: accuracy {best(z)[0]:.2f} at {best(z)[1]:.3g}" for n, z in
                           (("lr x lam0", x), ("lam0", lam), ("window", win))) + f" (n = {len(y)}, {y.mean():.2f} descended).", ""]
    with open(os.path.join(R, "tables_followup.md"), "w") as fh:
        fh.write("\n".join(md))
    print("wrote tables_followup.md, fig8_long_horizon.pdf, fig9_trainability.pdf")


if __name__ == "__main__":
    main()
