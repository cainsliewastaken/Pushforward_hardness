"""Collect every run's measurements into tables and the seven plots (plus a training-convergence plot).

  python aggregate.py            -> <out_root>/figs/*.pdf, <out_root>/tables/*.csv, <out_root>/tables.md
Numbers in tables are over seeds: mean [min, max], at the final checkpoint unless stated.
"""
import argparse
import json
import os

import matplotlib
import numpy as np
import torch

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from msr.config import load_cfg, run_dir, run_tag  # noqa: E402

PROTOS = [("onestep", "scratch"), ("unroll032", "scratch"), ("unroll064", "scratch"),
          ("unroll032", "ft"), ("unroll064", "ft")]
PLAB = {("onestep", "scratch"): "one-step", ("unroll032", "scratch"): "L_p, T=0.32 (scratch)",
        ("unroll064", "scratch"): "L_p, T=0.64 (scratch)", ("unroll032", "ft"): "L_p, T=0.32 (fine-tuned)",
        ("unroll064", "ft"): "L_p, T=0.64 (fine-tuned)"}
PCOL = dict(zip(PROTOS, ["black", "tab:blue", "tab:red", "tab:cyan", "tab:orange"]))
CLS = ["euler", "direct"]
LS = dict(euler="-", direct="--")
MK = dict(euler="o", direct="s")


def load(cfg):
    D = {}
    for dt in cfg["dts"]:
        for proto, init in PROTOS:
            f = os.path.join(run_dir(cfg, dt, proto, init), "meas.pt")
            if os.path.exists(f):
                for (cls, seed, step), r in torch.load(f, weights_only=False).items():
                    D[(dt, proto, init, cls, seed, step)] = r
    return D


def final(D, dt, proto, init, cls):
    """Measurements of each seed at its final checkpoint."""
    keys = [k for k in D if k[:4] == (dt, proto, init, cls)]
    if not keys:
        return []
    s = max(k[5] for k in keys)
    return [D[k] for k in keys if k[5] == s and not D[k].get("diverged")]


def stat(vals):
    v = np.array([x for x in vals if np.isfinite(x)])
    return (np.nan,) * 3 if v.size == 0 else (v.mean(), v.min(), v.max())


def fmt(t):
    m, lo, hi = t
    return "n/a" if not np.isfinite(m) else f"{m:.3g} [{lo:.3g}, {hi:.3g}]"


def md_table(title, rowname, rows, cols, cell):
    out = [f"### {title}", "", "| " + rowname + " | " + " | ".join(cols) + " |",
           "|" + "---|" * (len(cols) + 1)]
    for r in rows:
        out.append(f"| {r} | " + " | ".join(cell(r, c) for c in cols) + " |")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cfg", default="config.yaml")
    ap.add_argument("--set", nargs="*", default=[])
    a = ap.parse_args()
    cfg = load_cfg(a.cfg, a.set)
    R = cfg["out_root"]
    figs, tabs = os.path.join(R, "figs"), os.path.join(R, "tables")
    os.makedirs(figs, exist_ok=True)
    os.makedirs(tabs, exist_ok=True)
    D = load(cfg)
    dts, Ts = cfg["dts"], cfg["horizons"]
    dcol = dict(zip(dts, plt.cm.viridis(np.linspace(0, 0.85, len(dts)))))
    kT = len(Ts) - 1                                                   # index of T_final = 1.28
    md = ["# Tables (generated by aggregate.py)", "",
          "Over the 3 seeds: mean [min, max]. Final checkpoint, held-out starts.", ""]
    cols = [f"{c} / {PLAB[p]}" for c in CLS for p in PROTOS]

    def colkey(c):
        cls, lab = c.split(" / ")
        return cls, [p for p in PROTOS if PLAB[p] == lab][0]

    def cellf(field, idx):
        def cell(dt, c):
            cls, (proto, init) = colkey(c)
            return fmt(stat([r[field][idx] for r in final(D, dt, proto, init, cls)]))
        return cell

    # ---------- identity checks
    chk = {}
    cj = os.path.join(R, "checks.json")
    if os.path.exists(cj):
        chk = json.load(open(cj))
    trained = dict(Psi=[], gS=[], rec=[], rec_max_e=[])
    for k, r in D.items():
        if r.get("diverged"):
            continue
        if "chk_Psi_fd" in r:
            trained["Psi"].append(r["chk_Psi_fd"])
            trained["gS"].append(r["chk_gSigma_fd"])
        trained["rec"].append(np.nanmax(r["recon_relerr_t"][1:]))
    md.append("## Identity checks\n")
    if chk:
        for key, lab in [("chk_Jstate", "state Jacobian (forward mode) vs autograd"),
                         ("chk_Psi_fd", "Psi^(p) g vs central FD of the rollout"),
                         ("chk_gSigma_fd", "g^(Sigma)(p) vs FD of L_p"),
                         ("recon_max", f"reconstruction e(t_p) = sum P (eps + q), {cfg['gl_points']}-pt GL")]:
            md.append(f"- Pre-sweep, nontrivial random parameters, all classes and dt: {lab}: "
                      f"max rel. error {max(v[key] for v in chk.values()):.2e}")
    if trained["Psi"]:
        md.append(f"- Trained models (final checkpoints, T = 0.32 and 1.28): Psi g vs FD max {max(trained['Psi']):.2e}; "
                  f"g^(Sigma) vs FD max {max(trained['gS']):.2e}")
    if trained["rec"]:
        md.append(f"- Reconstruction at every checkpoint, model and p <= p(1.28): max rel. error {max(trained['rec']):.2e}")
    md.append("")

    # ---------- plot 1: R(1.28) vs dt
    fig, ax = plt.subplots(figsize=(6.4, 4.4))
    for pr in PROTOS:
        for cls in CLS:
            s = [stat([r["R"][kT] for r in final(D, dt, *pr, cls)]) for dt in dts]
            m = np.array([x[0] for x in s])
            ax.errorbar(dts, m, yerr=[m - [x[1] for x in s], [x[2] for x in s] - m], color=PCOL[pr], ls=LS[cls],
                        marker=MK[cls], ms=4, capsize=2, label=f"{cls}, {PLAB[pr]}")
    ax.set_xscale("log")
    ax.set_yscale("symlog", linthresh=1e-3)
    ax.axhline(0, color="gray", lw=0.5)
    ax.set_xlabel(r"$\Delta t$")
    ax.set_ylabel(r"$R(T{=}1.28)=|e(t_p)|-|\sum_{i<p}\epsilon_i|$")
    ax.legend(fontsize=6, ncol=2)
    fig.tight_layout()
    fig.savefig(os.path.join(figs, "fig1_R_vs_dt.pdf"))
    plt.close(fig)
    md.append(md_table("Plot 1: R(T=1.28)", "dt", dts, cols, cellf("R", kT)))
    md.append(md_table("Plot 1 (context): |e(T=1.28)|", "dt", dts, cols, cellf("e_norm", kT)))
    md.append(md_table("Plot 1 (context): I(T=1.28)", "dt", dts, cols, cellf("I", kT)))

    # ---------- plot 2: mean(rho - 1) vs dt
    fig, axs = plt.subplots(1, 2, figsize=(10, 4))
    for ax, cls in zip(axs, CLS):
        for pr in PROTOS:
            s = [stat([r["rho_m1"][kT] for r in final(D, dt, *pr, cls)]) for dt in dts]
            m = np.array([x[0] for x in s])
            ax.errorbar(dts, np.abs(m), yerr=None, color=PCOL[pr], marker=MK[cls], label=PLAB[pr] + ("" if np.all(m < 0) else " (sign varies)"))
        d = np.array(dts)
        ref = [np.abs(np.nanmean([r["rho_m1"][kT] for r in final(D, dts[0], *PROTOS[0], cls)]))]
        if np.isfinite(ref[0]):
            ax.plot(d, ref[0] * d / d[0], color="gray", ls=":", label=r"$\propto\Delta t$")
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xlabel(r"$\Delta t$")
        ax.set_ylabel(r"$|\Delta t\,\overline{n^\top\nabla H n}|$" if cls == "euler" else r"$|\overline{\rho}-1|$")
        ax.set_title(f"{cls} (mean over starts and steps i < p(1.28))", fontsize=9)
        ax.legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(os.path.join(figs, "fig2_contraction_vs_dt.pdf"))
    plt.close(fig)
    md.append(md_table("Plot 2: mean(rho - 1) over i < p(1.28) (Euler: = dt n.gradH.n)", "dt", dts, cols, cellf("rho_m1", kT)))
    md.append(md_table("Plot 2 (context): mean(rhobar - 1)", "dt", dts, cols, cellf("rhob_m1", kT)))
    md.append(md_table("Plot 2 (context): truth map mean(rho^f - 1)", "dt", dts, cols, cellf("rhof_m1", kT)))

    def grid(field, ylab, fname, logy=False, y_of=None, title=None):
        fig, axs = plt.subplots(2, len(PROTOS), figsize=(3.1 * len(PROTOS), 5.6), sharex=True, sharey=True)
        for i, cls in enumerate(CLS):
            for j, pr in enumerate(PROTOS):
                ax = axs[i, j]
                for dt in dts:
                    rs = final(D, dt, *pr, cls)
                    if not rs:
                        continue
                    if y_of is None:
                        Y = np.array([r[field] for r in rs])
                        x = (np.arange(Y.shape[1]) + 1) * dt
                    else:
                        x, Y = y_of(rs, dt)
                    ax.plot(x, Y.mean(0), color=dcol[dt], label=f"dt={dt:g}")
                    ax.fill_between(x, Y.min(0), Y.max(0), color=dcol[dt], alpha=0.2, lw=0)
                if logy:
                    ax.set_yscale("log")
                ax.set_title(f"{cls}, {PLAB[pr]}", fontsize=7)
                if i == 1:
                    ax.set_xlabel("physical time T")
                if j == 0:
                    ax.set_ylabel(ylab)
        axs[0, 0].legend(fontsize=6)
        if title:
            fig.suptitle(title, fontsize=9)
        fig.tight_layout()
        fig.savefig(os.path.join(figs, fname))
        plt.close(fig)

    # ---------- plot 3: c_Sigma(p) vs T
    grid("c_Sigma", r"$c_\Sigma(p)=\cos\angle(\hat g^{(1)},\hat g^{(\Sigma)}(p))$", "fig3_cSigma_vs_T.pdf")
    grid("c_q", r"$\cos\angle(\hat g^{(1)},\hat g^{(q)})$", "fig3b_cq_vs_T.pdf")

    def cS_at(field):
        def cell(dt, c):
            cls, pr = colkey(c)
            out = []
            for T in Ts:
                p = int(round(T / dt))
                out.append(fmt(stat([r[field][p - 1] for r in final(D, dt, *pr, cls)])).split(" [")[0])
            return " / ".join(out)
        return cell
    md.append(md_table("Plot 3: c_Sigma at T = " + ", ".join(map(str, Ts)) + " (seed means)", "dt", dts, cols, cS_at("c_Sigma")))
    md.append(md_table("Plot 3b: per-horizon cos(g1, g^(q)) at the same T (seed means)", "dt", dts, cols, cS_at("c_q")))

    # ---------- plot 4: sum ln rhobar vs R(T)
    fig, ax = plt.subplots(figsize=(6, 4.6))
    rows4 = []
    for (dt, proto, init, cls, seed, step), r in D.items():
        if r.get("diverged"):
            continue
        rs = final(D, dt, proto, init, cls)
        if not any(x is r for x in rs):
            continue
        for k in range(len(Ts)):
            rows4.append((dt, proto, init, cls, seed, Ts[k], r["sum_ln_rhob"][k], r["R"][k], r["e_norm"][k], r["I"][k]))
        ax.scatter(r["R"], r["sum_ln_rhob"], s=10, color=dcol[dt], marker=MK[cls], alpha=0.7)
    for dt in dts:
        ax.scatter([], [], color=dcol[dt], label=f"dt={dt:g}")
    for cls in CLS:
        ax.scatter([], [], color="gray", marker=MK[cls], label=cls)
    ax.set_xscale("symlog", linthresh=1e-4)
    ax.set_xlabel(r"measured $R(T)$")
    ax.set_ylabel(r"$\langle\sum_{i<p}\ln|\bar\rho_i|\rangle_k$")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(os.path.join(figs, "fig4_sumlnrho_vs_R.pdf"))
    plt.close(fig)
    np.savetxt(os.path.join(tabs, "plot4_scatter.csv"), np.array([list(map(str, x)) for x in rows4]), fmt="%s",
               delimiter=",", header="dt,proto,init,cls,seed,T,sum_ln_rhob,R,e_norm,I", comments="")
    md.append(md_table("Plot 4: sum_i ln|rhobar_i| at T = " + ", ".join(map(str, Ts)) + " (seed means; full scatter in tables/plot4_scatter.csv)",
                       "dt", dts, cols, lambda dt, c: " / ".join(
                           fmt(stat([r["sum_ln_rhob"][k] for r in final(D, dt, *colkey(c)[1], colkey(c)[0])])).split(" [")[0]
                           for k in range(len(Ts)))))

    # ---------- plot 5: |sum P q| / |e| vs T
    def ratio_curve(rs, dt):
        return np.array(Ts), np.array([r["ratio_q"] for r in rs])
    grid(None, r"$|\sum_i\hat P\mathbf{q}_i|/|e(t_p)|$", "fig5_nonlinear_ratio_vs_T.pdf", logy=True, y_of=ratio_curve)
    for f, lab in [("ratio_q", "Plot 5: |sum P q| / |e(t_p)|"), ("S_eps", "Plot 5 (context): |sum P eps|"),
                   ("S_q", "Plot 5 (context): |sum P q|")]:
        md.append(md_table(f"{lab} at T = " + ", ".join(map(str, Ts)) + " (seed means)", "dt", dts, cols,
                           lambda dt, c, f=f: " / ".join(
                               f"{np.nanmean([r[f][k] for r in final(D, dt, *colkey(c)[1], colkey(c)[0])]):.3g}"
                               for k in range(len(Ts)))))

    # ---------- plot 6: R_e(H) vs max(1-rho)/dt; one-step vs unrolled
    fig, axs = plt.subplots(1, 2, figsize=(11, 4.4))
    ax = axs[0]
    for dt in dts:
        for pr in PROTOS:
            for cls in CLS:
                for r in final(D, dt, *pr, cls):
                    ax.scatter(r["max_1m_rho_dt"][kT], r["Re_H"][kT], color=dcol[dt], marker=MK[cls], s=14, alpha=0.8)
    lim = ax.get_xlim()
    ax.plot([1e-3, 1e4], [1e-3, 1e4], color="gray", lw=0.6, ls=":")
    ax.set_xscale("symlog", linthresh=1e-2)
    ax.set_yscale("log")
    ax.set_xlabel(r"$\max_{k,i}(1-\rho_i)/\Delta t$")
    ax.set_ylabel(r"$\mathcal{R}_e(H)$")
    ax.set_title("T = 1.28, all models (colour dt, marker class)", fontsize=8)
    ax = axs[1]
    for pr in PROTOS:
        for cls in CLS:
            s = [stat([r["Re_H"][kT] for r in final(D, dt, *pr, cls)]) for dt in dts]
            m = np.array([x[0] for x in s])
            ax.errorbar(dts, m, yerr=[m - [x[1] for x in s], [x[2] for x in s] - m], color=PCOL[pr], ls=LS[cls],
                        marker=MK[cls], ms=4, capsize=2, label=f"{cls}, {PLAB[pr]}")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(r"$\Delta t$")
    ax.set_ylabel(r"$\mathcal{R}_e(H)$, T = 1.28")
    ax.legend(fontsize=6, ncol=2)
    fig.tight_layout()
    fig.savefig(os.path.join(figs, "fig6_Re_H.pdf"))
    plt.close(fig)
    md.append(md_table("Plot 6: R_e(H), T = 1.28", "dt", dts, cols, cellf("Re_H", kT)))
    md.append(md_table("Plot 6: max (1 - rho)/dt, T = 1.28", "dt", dts, cols, cellf("max_1m_rho_dt", kT)))
    md.append(md_table("Plot 6 (context): R_e(H - f_dt), T = 1.28", "dt", dts, cols, cellf("Re_H_minus_f", kT)))
    md.append(md_table("M6: spectral norm of M (upper bound on sigma_e), T = 1.28", "dt", dts, cols, cellf("M6_spec", kT)))
    md.append(md_table("M6: largest row norm of M (lower bound on sigma_e), T = 1.28", "dt", dts, cols, cellf("M6_maxrow", kT)))

    # ---------- plot 7: lambda_max(K^(p)) vs T
    def lam_curve(rs, dt):
        return np.array(Ts), np.array([r["K_lam_max"] for r in rs])
    grid(None, r"$\lambda_{\max}(K^{(p)})$", "fig7_Klam_vs_T.pdf", logy=True, y_of=lam_curve)
    for f, lab in [("K_lam_max", "Plot 7: lambda_max(K^(p))"), ("K_tr_over_lam", "M7: tr K / lambda_max"),
                   ("PT_ehat", "M7: |P^T ehat| / |ehat|")]:
        md.append(md_table(f"{lab} at T = " + ", ".join(map(str, Ts)) + " (seed means)", "dt", dts, cols,
                           lambda dt, c, f=f: " / ".join(
                               f"{np.nanmean([r[f][k] for r in final(D, dt, *colkey(c)[1], colkey(c)[0])]):.3g}"
                               for k in range(len(Ts)))))

    # ---------- training convergence (evidence that runs are trained)
    fig, axs = plt.subplots(2, len(PROTOS), figsize=(3.1 * len(PROTOS), 5.6), sharey="row")
    for j, pr in enumerate(PROTOS):
        for dt in dts:
            f = os.path.join(run_dir(cfg, dt, *pr), "log.csv")
            if not os.path.exists(f):
                continue
            L = np.genfromtxt(f, delimiter=",", names=True)
            for cls in CLS:
                one = np.array([L[f"onestep_{cls}{s}"] for s in cfg["seeds"]])
                eT = np.array([L[f"eT_{cls}{s}"] for s in cfg["seeds"]])
                axs[0, j].loglog(np.maximum(L["step"], 1), one.mean(0), color=dcol[dt], ls=LS[cls])
                axs[1, j].loglog(np.maximum(L["step"], 1), eT.mean(0), color=dcol[dt], ls=LS[cls])
        axs[0, j].set_title(PLAB[pr], fontsize=7)
        axs[1, j].set_xlabel("Adam step")
    axs[0, 0].set_ylabel("held-out one-step loss")
    axs[1, 0].set_ylabel("held-out |e(T=0.64)|")
    for dt in dts:
        axs[0, 0].plot([], [], color=dcol[dt], label=f"dt={dt:g}")
    for cls in CLS:
        axs[0, 0].plot([], [], color="gray", ls=LS[cls], label=cls)
    axs[0, 0].legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(os.path.join(figs, "fig0_training.pdf"))
    plt.close(fig)

    # checkpoint evolution of R(1.28) (all checkpoints) as a CSV
    rows = [(k[0], k[1], k[2], k[3], k[4], k[5], r["R"][kT], r["e_norm"][kT], r["I"][kT], r["rho_m1"][kT])
            for k, r in sorted(D.items()) if not r.get("diverged")]
    np.savetxt(os.path.join(tabs, "all_checkpoints_T1.28.csv"), np.array([list(map(str, x)) for x in rows]), fmt="%s",
               delimiter=",", header="dt,proto,init,cls,seed,step,R,e_norm,I,rho_m1", comments="")
    div = [k for k, r in D.items() if r.get("diverged")]
    md.append(f"\nDiverged (non-finite) model checkpoints: {len(div)}" + (f": {div}" if div else ""))
    with open(os.path.join(R, "tables.md"), "w") as fh:
        fh.write("\n".join(md))
    print(f"{len(D)} model-checkpoints aggregated; figures in {figs}")


if __name__ == "__main__":
    main()
